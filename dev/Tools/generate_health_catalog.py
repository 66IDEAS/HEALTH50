#!/usr/bin/env python3
"""Generate HealthCatalog+Generated.swift from the HealthKit headers of the installed iOS SDK.

The app must export every non-clinical data type Health offers to apps. Instead of a hand-kept
list, this reads Apple's headers so a new SDK only needs a re-run:

    python3 Tools/generate_health_catalog.py Health50/Health/HealthCatalog+Generated.swift

It extracts
  - all quantity type identifiers,
  - all category type identifiers with the value enum Apple documents for each,
  - the case names of every category value enum,
  - the case names of HKWorkoutActivityType.
Deprecated identifiers and cases are skipped.
"""
import re
import subprocess
import sys
from pathlib import Path

sdk = subprocess.run(["xcrun", "--sdk", "iphonesimulator", "--show-sdk-path"],
                     capture_output=True, text=True, check=True).stdout.strip()
sdk_version = subprocess.run(["xcrun", "--sdk", "iphonesimulator", "--show-sdk-version"],
                             capture_output=True, text=True, check=True).stdout.strip()
headers = Path(sdk) / "System/Library/Frameworks/HealthKit.framework/Headers"

ids = (headers / "HKTypeIdentifiers.h").read_text()


def usable(line: str) -> bool:
    return "API_DEPRECATED" not in line and "API_UNAVAILABLE(ios" not in line


quantities = []
for m in re.finditer(r"^HK_EXTERN HKQuantityTypeIdentifier const (HKQuantityTypeIdentifier\w+)(.*)$", ids, re.M):
    if usable(m.group(2)):
        # Apple documents the canonical unit in the trailing comment: "// count/s, Discrete (Temporally Weighted)"
        hint = re.search(r"//\s*([^,]*),", m.group(2))
        quantities.append((m.group(1), hint.group(1).strip() if hint else ""))

# Identifiers whose value in HealthKit differs from the name of the constant in the header.
# Apple renamed the constant but kept the stored identifier.
RAW_VALUES = {
    "HKCategoryTypeIdentifierEnvironmentalAudioExposureEvent": "HKCategoryTypeIdentifierAudioExposureEvent",
}

categories = {}
for m in re.finditer(r"^HK_EXTERN HKCategoryTypeIdentifier const (HKCategoryTypeIdentifier\w+)(.*)$", ids, re.M):
    if not usable(m.group(2)):
        continue
    enum = re.search(r"//\s*(HKCategoryValue\w*)", m.group(2))
    categories[RAW_VALUES.get(m.group(1), m.group(1))] = enum.group(1) if enum else "HKCategoryValue"


def lower_first(name: str) -> str:
    # "REM" style prefixes stay readable: AsleepREM -> asleepREM, HIIT -> hiit handled by caller
    return name[0].lower() + name[1:] if name else name


def parse_enum(text: str, enum_name: str) -> dict:
    m = re.search(r"typedef NS_ENUM\(\s*\w+\s*,\s*" + enum_name + r"\s*\)\s*\{(.*?)\}", text, re.S)
    if not m:
        return {}
    cases, value = {}, -1
    body = re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)
    for raw in body.split("\n"):
        line = raw.split("//")[0].strip().rstrip(",")
        cm = re.match(r"(" + enum_name + r"\w+)", line)
        if not cm:
            continue
        explicit = re.search(r"=\s*(-?\d+)\s*$", line)
        value = int(explicit.group(1)) if explicit else value + 1
        if "API_DEPRECATED" in line:
            continue
        cases.setdefault(value, lower_first(cm.group(1)[len(enum_name):]))
    return cases


values_h = (headers / "HKCategoryValues.h").read_text()
value_enums = {}
for enum_name in sorted(set(categories.values())):
    cases = parse_enum(values_h, enum_name)
    if cases:
        value_enums[enum_name] = cases

workout_h = (headers / "HKWorkoutActivityType.h").read_text()
activities = parse_enum(workout_h, "HKWorkoutActivityType")
if not activities:
    sys.exit("could not parse HKWorkoutActivityType")


# Other enums whose case names appear in the export (searched in all HealthKit headers).
OTHER_ENUMS = [
    "HKStateOfMindLabel", "HKStateOfMindAssociation", "HKStateOfMindKind", "HKStateOfMindValenceClassification",
    "HKElectrocardiogramClassification", "HKElectrocardiogramSymptomsStatus", "HKWorkoutEventType",
    "HKBiologicalSex", "HKBloodType", "HKFitzpatrickSkinType", "HKWheelchairUse",
    "HKGAD7AssessmentRisk", "HKPHQ9AssessmentRisk",
]
all_headers = "\n".join(h.read_text() for h in sorted(headers.glob("*.h")))
other_enums = {}
for enum_name in OTHER_ENUMS:
    cases = parse_enum(all_headers, enum_name)
    if not cases:
        sys.exit(f"could not parse {enum_name}")
    other_enums[enum_name] = cases


def swift_string_array(items, indent="        "):
    return "\n".join(f'{indent}"{i}",' for i in items)


def swift_int_map(d, indent="            "):
    return "\n".join(f'{indent}{k}: "{v}",' for k, v in sorted(d.items()))


out = f"""// Generated by Tools/generate_health_catalog.py from the iOS {sdk_version} SDK. Do not edit by hand.
// Re-run the script after installing a new SDK.

enum GeneratedHealthCatalog {{
    /// Every quantity type identifier the SDK offers on iOS, with Apple's canonical unit ({len(quantities)}).
    static let quantityIdentifiers: [(identifier: String, unit: String)] = [
{chr(10).join(f'        ("{k}", "{v}"),' for k, v in quantities)}
    ]

    /// Every category type identifier with the value enum Apple documents for it ({len(categories)}).
    static let categoryIdentifiers: [(identifier: String, valueEnum: String)] = [
{chr(10).join(f'        ("{k}", "{v}"),' for k, v in categories.items())}
    ]

    /// Readable names of the category values, per value enum.
    static let categoryValueNames: [String: [Int: String]] = [
{chr(10).join(f'        "{name}": [{chr(10)}{swift_int_map(cases)}{chr(10)}        ],' for name, cases in value_enums.items())}
    ]

    /// Readable names of other enums used in the export, per enum.
    static let enumNames: [String: [Int: String]] = [
{chr(10).join(f'        "{name}": [{chr(10)}{swift_int_map(cases)}{chr(10)}        ],' for name, cases in other_enums.items())}
    ]

    /// Readable names of HKWorkoutActivityType ({len(activities)}).
    static let workoutActivityNames: [Int: String] = [
{swift_int_map(activities, "        ")}
    ]
}}
"""
target = Path(sys.argv[1])
target.parent.mkdir(parents=True, exist_ok=True)
target.write_text(out)
print(f"SDK {sdk_version}: {len(quantities)} quantity types, {len(categories)} category types, "
      f"{len(value_enums)} value enums, {len(activities)} workout activities -> {target}")
